package dto

import contractdto "github.com/gatework/motor-core/sdk/contract/dto"

// AutoForm and the types below describe a form built by go-admin-ui's form
// designer. They are thin aliases of motor-core's sdk/contract/dto (PRD
// 006 F2/F5).
type (
	// AutoForm uses the canonical core DTO contract.
	AutoForm = contractdto.AutoForm
	// Config uses the canonical core DTO contract.
	Config = contractdto.Config
	// Option uses the canonical core DTO contract.
	Option = contractdto.Option
	// Slot uses the canonical core DTO contract.
	Slot = contractdto.Slot
	// Field uses the canonical core DTO contract.
	Field = contractdto.Field
	// Style uses the canonical core DTO contract.
	Style = contractdto.Style
)
